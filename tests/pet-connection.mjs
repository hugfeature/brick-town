import assert from 'node:assert/strict';
import {parseFamilyKey,familyLink,connectionHint,CLOUD_ORIGIN} from '../pet/connection.mjs';
const key='a'.repeat(48);
assert.equal(parseFamilyKey(familyLink(key)),key);
assert.equal(parseFamilyKey(familyLink(key,true)),key,'standalone page retains exact existing family');
assert.equal(parseFamilyKey('  '+key+'  '),key);
assert.equal(parseFamilyKey('https://evil.invalid/#home='+key),'');
assert.equal(parseFamilyKey('https://hugfeature.github.io/brick-town/pet/'),'');
assert.equal(familyLink('',true),'');
assert.equal(new URL(familyLink(key,true)).origin,CLOUD_ORIGIN);
assert.equal(new URL(familyLink(key,true)).search,'','family secret stays in fragment, not query');
assert.match(connectionHint({hasKey:true,connected:false}).detail,/重新连接/);
assert.match(connectionHint({hasKey:true,connected:false}).detail,/Safari/);
assert.match(connectionHint({hasKey:true,offline:true}).title,/没有联网/);
assert.match(connectionHint({hasKey:true,missing:true}).detail,/原手机/);
assert.match(connectionHint({hasKey:true,pending:true,working:true}).title,/确认上次保存/);
assert.match(connectionHint({hasKey:false}).detail,/家庭口令/);
assert.match(connectionHint({hasKey:true,connected:true}).title,/已连接/);
console.log('PASS: family link/code parsing, same-family standalone URL, no token in query, actionable connection states.');
